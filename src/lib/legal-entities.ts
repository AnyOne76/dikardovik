export function isLegalEntityId(value: unknown): value is LegalEntityId {
  return typeof value === "string" && (LEGAL_ENTITY_IDS as readonly string[]).includes(value);
}

export function getLegalEntity(id?: string | null): LegalEntity {
  const found = LEGAL_ENTITIES.find((entity) => entity.id === id);
  return found ?? LEGAL_ENTITIES[0];
}
